package com.perficient.restassured.pojo;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;

/**
 * POJO (Plain Old Java Object) for a GoRest user (Bonus Assignment).
 * Used both to BUILD the request body and to READ the response body, so tests
 * work with Java objects instead of hand-written JSON strings.
 */
@JsonInclude(JsonInclude.Include.NON_NULL)       // do not send fields that are null (e.g. id on create)
@JsonIgnoreProperties(ignoreUnknown = true)      // ignore extra fields returned by the server
public class User {

    private Integer id;      // generated by the server
    private String name;
    private String email;    // must be unique on the server
    private String gender;   // "male" or "female"
    private String status;   // "active" or "inactive"

    /** Required by Jackson for deserialization. */
    public User() {
    }

    /** Convenience constructor for creating a user (id is assigned by the server). */
    public User(String name, String email, String gender, String status) {
        this.name = name;
        this.email = email;
        this.gender = gender;
        this.status = status;
    }

    public Integer getId() { return id; }
    public void setId(Integer id) { this.id = id; }
    public String getName() { return name; }
    public void setName(String name) { this.name = name; }
    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }
    public String getGender() { return gender; }
    public void setGender(String gender) { this.gender = gender; }
    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }
}
